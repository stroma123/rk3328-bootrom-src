/*
 * bootrom_rodata.c - constant tables embedded in the ROM .rodata.
 *
 * Exact bytes transcribed from the binary:
 *   - usb_device_descriptor : 0xffff46a8 (18 bytes)
 *   - usb_config_descriptor : 0xffff46bc (32 bytes)
 *   - rc4_init_table        : 0xffff46e0 (64 x 32-bit words; the ROM stores
 *                             each as the low word of an 8-byte slot and copies
 *                             only the low 4 bytes into the RC4 S-box)
 */
